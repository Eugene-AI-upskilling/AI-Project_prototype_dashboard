const { chromium } = require('../../insightlab-showreel/node_modules/playwright');
const fs = require('fs');
const path = require('path');
const base = 'http://127.0.0.1:4190/';
const files = { a: 'a-signal.html', b: 'b-vector.html', c: 'c-orbit.html', d: 'd-redshift.html' };
(async () => {
  const browser = await chromium.launch({ headless: true, args: ['--enable-webgl', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
  const results = [];
  const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(base);
  await page.waitForFunction(() => document.body.dataset.reviewReady === 'true');
  await page.screenshot({ path: path.join(__dirname, 'compare-desktop.png') });
  const overflow = () => page.evaluate(() => document.documentElement.scrollWidth > innerWidth);
  const load = async (id, side = 'left') => {
    if (side === 'left') await page.locator(`[data-preview="${id}"]`).click();
    else await page.locator('#second-concept').selectOption(id);
    const handle = await page.locator(`#${side}-frame`).elementHandle();
    const frame = await handle.contentFrame();
    await frame.waitForURL(new RegExp(files[id].replace('.', '\\.')));
    await frame.waitForSelector('main');
    await frame.evaluate(() => document.fonts.ready);
    await page.waitForTimeout(300);
    return frame;
  };
  await page.locator('#live').scrollIntoViewIfNeeded();
  const desktop = { mode: 'desktop', overflow: await overflow(), tabs: [] };
  for (const id of ['a', 'b', 'c', 'd']) {
    const frame = await load(id);
    desktop.tabs.push({ id, url: frame.url(), viewport: await frame.evaluate(() => ({ width: innerWidth, height: innerHeight })), title: await frame.title() });
  }
  const d = await page.locator('#left-frame').elementHandle().then(handle => handle.contentFrame());
  await page.locator('#left-frame').scrollIntoViewIfNeeded();
  const rect = await page.locator('#left-frame').boundingBox();
  await page.mouse.move(Math.max(100, rect.x + Math.min(rect.width * .5, 700)), Math.max(100, Math.min(700, rect.y + 250)));
  await page.mouse.wheel(0, 650);
  await page.waitForTimeout(500);
  desktop.childDScroll = await d.evaluate(() => ({ scroll: scrollY, progress: document.querySelector('.shift').dataset.progress, fold: getComputedStyle(document.querySelector('.shift')).getPropertyValue('--fold') }));
  await page.locator('#device').selectOption('mobile');
  await page.waitForTimeout(300);
  desktop.mobileFrameViewport = await d.evaluate(() => ({ width: innerWidth, height: innerHeight }));
  await page.locator('#device').selectOption('desktop');
  await load('c');
  await page.locator('#split-toggle').click();
  await page.waitForTimeout(300);
  desktop.split = { visible: await page.locator('#right-pane').isVisible(), rightChoices: [] };
  for (const id of ['b', 'c', 'd']) {
    const frame = await load(id, 'right');
    desktop.split.rightChoices.push({ id, url: frame.url(), viewport: await frame.evaluate(() => ({ width: innerWidth, height: innerHeight })) });
  }
  await page.locator('#live').scrollIntoViewIfNeeded();
  await page.screenshot({ path: path.join(__dirname, 'compare-split.png') });
  const right = await page.locator('#right-frame').elementHandle().then(handle => handle.contentFrame());
  await right.evaluate(() => window.__qaReloadMarker = true);
  await page.locator('#reset-preview').click();
  await page.waitForTimeout(700);
  const resetRight = await page.locator('#right-frame').elementHandle().then(handle => handle.contentFrame());
  desktop.resetReloaded = await resetRight.evaluate(() => !window.__qaReloadMarker && scrollY === 0);
  await page.locator('#split-toggle').click();
  desktop.splitHidden = !(await page.locator('#right-pane').isVisible());
  desktop.rightSourceRemoved = await page.locator('#right-frame').getAttribute('src') === null;
  desktop.errors = [...errors];
  results.push(desktop);
  await page.close();
  const mobile = await browser.newPage({ viewport: { width: 390, height: 844 } });
  const mobileErrors = [];
  mobile.on('pageerror', error => mobileErrors.push(error.message));
  await mobile.goto(base);
  await mobile.waitForFunction(() => document.body.dataset.reviewReady === 'true');
  await mobile.screenshot({ path: path.join(__dirname, 'compare-mobile.png') });
  await mobile.locator('#device').selectOption('mobile');
  await mobile.locator('[data-preview="b"]').click();
  await mobile.waitForTimeout(700);
  const mobileChild = await mobile.locator('#left-frame').elementHandle().then(handle => handle.contentFrame());
  const mob = { mode: 'mobile', overflow: await mobile.evaluate(() => document.documentElement.scrollWidth > innerWidth), childViewport: await mobileChild.evaluate(() => ({ width: innerWidth, height: innerHeight })), url: mobileChild.url(), errors: mobileErrors };
  await mobile.locator('#live').scrollIntoViewIfNeeded();
  await mobile.screenshot({ path: path.join(__dirname, 'compare-mobile-live.png') });
  results.push(mob);
  await mobile.close();
  await browser.close();
  fs.writeFileSync(path.join(__dirname, 'compare-results.json'), JSON.stringify(results, null, 2));
  console.log(JSON.stringify(results, null, 2));
})().catch(error => { console.error(error); process.exit(1); });
